const norm = (s: string) => s.normalize('NFKC').replace(/\s+/g, '');
/** 名前（複数）から種類を見つける。同じ種類は1回だけ */
export function drugClassesFromNames(names: string[]): DrugNameHit[] {
  const out: DrugNameHit[] = [];
  for (const raw of names) {
    const n = norm(raw);
    if (!n) continue;
    for (const d of DRUG_NAMES) {
      const w = d.words.find((x) => n.includes(norm(x)));
      if (w && !out.some((o) => o.flag === d.flag)) out.push({ flag: d.flag, label: d.label, word: w });
    }
  }
  return out;
}
